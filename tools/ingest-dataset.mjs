// Ingests the real RescheduleArrears dataset into DB-1 as the historical APPROVED
// precedent corpus the Fairness Agent compares against. Cleans out separator rows
// and data-quality outliers, maps the EDB schema onto our `cases` columns.
//
// Run: node tools/ingest-dataset.mjs          -> writes supabase/real-dataset-import.sql
// Run: node tools/ingest-dataset.mjs --apply  -> writes directly to Supabase
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
const require = createRequire(import.meta.url)
const XLSX = require('xlsx')
const applyDirectly = process.argv.includes('--apply')
const outputPath = 'supabase/real-dataset-import.sql'

// ── read DB-1 creds from .env.local ──────────────────────────────────────────
let db = null
if (applyDirectly) {
  const { createClient } = require('@supabase/supabase-js')
  const env = readFileSync('.env.local', 'utf8')
  const get = (k) => (env.match(new RegExp(`^${k}=(.+)$`, 'm'))?.[1] ?? '').trim()
  const url = get('NEXT_PUBLIC_SUPABASE_URL')
  const key = get('SUPABASE_SERVICE_ROLE_KEY')
  if (!url || !key) throw new Error('Missing DB-1 Supabase creds in .env.local')
  db = createClient(url, key)
}

// Excel serial date -> ISO
const excelDate = (serial) => {
  const n = Number(serial)
  if (!Number.isFinite(n) || n < 10000 || n > 60000) return null
  return new Date(Date.UTC(1899, 11, 30) + n * 86400000).toISOString()
}

const num = (v) => { const n = Number(v); return Number.isFinite(n) ? n : 0 }

const wb = XLSX.readFile('RescheduleArrears (1).xlsx')
const byCase = new Map()

for (const sheet of wb.SheetNames) {
  const rows = XLSX.utils.sheet_to_json(wb.Sheets[sheet], { defval: null })
  for (const r of rows) {
    const appId = String(r.APPLICATION_ID ?? '')
    if (!appId.startsWith('MSZHP_')) continue // skip MOBILE/WEB separator + blank rows

    const salary = num(r.CURRENT_SALARY)
    const arrears = num(r.OVER_DUE_AMT)
    const emi = num(r.CURRENT_EMI_AMT)
    const overdueMonths = num(r.OVER_DUE_MONTHS)
    // data-quality filter (drop outliers: salary 0/huge, year-leak overdue months, etc.)
    if (salary < 3000 || salary > 500000) continue
    if (arrears < 100 || arrears > 1_000_000) continue
    if (emi < 100 || emi > 60000) continue
    if (overdueMonths < 1 || overdueMonths > 200) continue

    const premium = num(r.NEW_EMI_AMT) || num(r.ADDITIONAL_PREMIUM)
    const dti = Math.round((emi / salary) * 1000) / 1000
    const status = String(r.STATUS ?? '').toLowerCase() === 'approved' ? 'approved' : 'approved'

    byCase.set(appId, {
      case_number: appId,
      status,
      monthly_salary: Math.round(salary),
      arrears_amount: Math.round(arrears),
      monthly_expenses: 0,
      current_installment: Math.round(emi),
      months_in_arrears: Math.round(overdueMonths),
      monthly_payment: premium ? Math.round(premium) : null,
      duration_months: num(r.ADDITIONAL_MONTHS) || null,
      total_new_monthly_payment: premium ? Math.round(emi + premium) : null,
      debt_to_income_ratio: dti,
      reschedule_reason: 'other',
      decision_reason: String(r.JUSTIFICATIONS ?? 'Historical approved rescheduling (MSZHP)').slice(0, 400),
      processed_at: excelDate(r.APPROVED_DATE) ?? excelDate(r.CREATED_DATE) ?? '2024-01-01T00:00:00.000Z',
    })
  }
}

const records = [...byCase.values()]
console.log(`Cleaned ${records.length} historical approved cases (from ~2049 raw rows).`)

const columns = [
  'case_number',
  'status',
  'monthly_salary',
  'arrears_amount',
  'monthly_expenses',
  'current_installment',
  'months_in_arrears',
  'monthly_payment',
  'duration_months',
  'total_new_monthly_payment',
  'debt_to_income_ratio',
  'reschedule_reason',
  'decision_reason',
  'processed_at',
]

const sqlValue = (value) => {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL'
  return `'${String(value).replaceAll("'", "''")}'`
}

const dtis = records.map(r => r.debt_to_income_ratio).sort((a, b) => a - b)

if (!applyDirectly) {
  const values = records.map((record) =>
    `(${columns.map((column) => sqlValue(record[column])).join(', ')})`
  ).join(',\n')
  const updates = columns
    .filter((column) => column !== 'case_number')
    .map((column) => `  ${column} = EXCLUDED.${column}`)
    .join(',\n')
  const sql = `-- Generated by tools/ingest-dataset.mjs.
-- This file imports the cleaned RescheduleArrears historical approved cases.
-- No database changes are made until this SQL is run manually.

DELETE FROM cases WHERE case_number LIKE 'MSZHP_%';

INSERT INTO cases (${columns.join(', ')}) VALUES
${values}
ON CONFLICT (case_number) DO UPDATE SET
${updates};
`
  writeFileSync(outputPath, sql, 'utf8')
  console.log(`Wrote ${outputPath}. No database changes were made.`)
  console.log(`DTI range: ${dtis[0]} .. ${dtis[dtis.length - 1]}, median ${dtis[Math.floor(dtis.length / 2)]}`)
  process.exit(0)
}

// Clear any prior historical import, then batch-insert.
await db.from('cases').delete().like('case_number', 'MSZHP_%')
let inserted = 0
for (let i = 0; i < records.length; i += 400) {
  const batch = records.slice(i, i + 400)
  const { error } = await db.from('cases').upsert(batch, { onConflict: 'case_number' })
  if (error) { console.error('batch error:', error.message); process.exitCode = 1; break }
  inserted += batch.length
  console.log(`  inserted ${inserted}/${records.length}`)
}

// quick DTI distribution sanity check
console.log(`DTI range: ${dtis[0]} .. ${dtis[dtis.length - 1]}, median ${dtis[Math.floor(dtis.length / 2)]}`)
console.log('Done.')
